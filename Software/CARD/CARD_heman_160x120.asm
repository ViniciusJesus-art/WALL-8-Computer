VIDEO_BUSY_MASK  = $01
VIDEO_END_MASK   = $10

VIDEO_CLEAR      = $00
VIDEO_MODE_160   = $13

FRAME_COUNT_RAM  = $0200

INICIO:
    CALL VIDEO_WAIT
    STI VIDEO_CMD, #VIDEO_MODE_160
    CALL VIDEO_WAIT
    STI VIDEO_CMD, #VIDEO_CLEAR
    CALL VIDEO_WAIT
    PTR FRAME_0

VIDEO_RESTART:
    STI FRAME_COUNT_RAM, #$05

NEXT_FRAME:
    CALL VIDEO_WAIT
    STI VIDEO_X, #$00
    STI VIDEO_Y, #$00

FRAME_WRITE_LOOP:
    LDA [PTR+]
    MOV B, A

FRAME_WAIT_BEFORE_WRITE:
    LDA VIDEO_STATUS
    TEST A, #VIDEO_BUSY_MASK
    JNZ FRAME_WAIT_BEFORE_WRITE

    MOV A, B
    STA VIDEO_DATA

FRAME_WAIT_FINISH:
    LDA VIDEO_STATUS
    TEST A, #VIDEO_BUSY_MASK
    JNZ FRAME_WAIT_FINISH

    LDA VIDEO_STATUS
    TEST A, #VIDEO_END_MASK
    JZ FRAME_WRITE_LOOP

    LDA FRAME_COUNT_RAM
    DEC A
    STA FRAME_COUNT_RAM
    JNZ NEXT_FRAME

    PTR FRAME_0
    JMP VIDEO_RESTART

VIDEO_WAIT:
    LDA VIDEO_STATUS
    TEST A, #VIDEO_BUSY_MASK
    JNZ VIDEO_WAIT
    RET


