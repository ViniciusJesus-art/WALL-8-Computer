START_PLAYER_BULLET:
    LDA PLAYER_BULLET_ACTIVE
    CMP A, #$01
    JZ START_PLAYER_BULLET_DONE
    LDA PLAYER_FIRE_COOLDOWN
    CMP A, #$00
    JNZ START_PLAYER_BULLET_DONE

    LDA PLAYER_DIR
    STA PLAYER_BULLET_DIR
    CMP A, #DIR_UP
    JZ START_PB_UP
    CMP A, #DIR_RIGHT
    JZ START_PB_RIGHT
    CMP A, #DIR_DOWN
    JZ START_PB_DOWN
    JMP START_PB_LEFT

START_PB_UP:
    LDA PLAYER_Y
    CMP A, #$00
    JZ START_PLAYER_BULLET_DONE
    DEC A
    STA BULLET_Y
    LDA PLAYER_X
    STA BULLET_X
    JMP START_PB_READY

START_PB_RIGHT:
    LDA PLAYER_X
    CMP A, #MAX_PLAYER_POS
    JZ START_PLAYER_BULLET_DONE
    ADD A, #$02
    STA BULLET_X
    LDA PLAYER_Y
    STA BULLET_Y
    JMP START_PB_READY

START_PB_DOWN:
    LDA PLAYER_Y
    CMP A, #MAX_PLAYER_POS
    JZ START_PLAYER_BULLET_DONE
    ADD A, #$02
    STA BULLET_Y
    LDA PLAYER_X
    STA BULLET_X
    JMP START_PB_READY

START_PB_LEFT:
    LDA PLAYER_X
    CMP A, #$00
    JZ START_PLAYER_BULLET_DONE
    DEC A
    STA BULLET_X
    LDA PLAYER_Y
    STA BULLET_Y

START_PB_READY:
