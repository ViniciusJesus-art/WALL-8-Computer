    CALL DRAW_BITMAP8

    CALL SYNC_FRAME_STATE

WAIT_END_SCREEN:
    CALL WAIT_FRAME_NO_INPUT
    CALL UPDATE_SOUND

    LDA SYSTEM_STATUS
    TEST A, #KEY_READY_MASK
    JZ WAIT_END_SCREEN

    LDA KEY_DATA
    CMP A, #$0D
    JZ END_SCREEN_RESTART
    CMP A, #$20
    JZ END_SCREEN_RESTART
    CMP A, #$4A
    JZ END_SCREEN_RESTART
    CMP A, #$6A
    JZ END_SCREEN_RESTART
    CMP A, #$51
    JZ END_SCREEN_EXIT
    CMP A, #$71
    JZ END_SCREEN_EXIT
    JMP WAIT_END_SCREEN

END_SCREEN_RESTART:
    STI SCREEN_ACTION, #$01
    RET

END_SCREEN_EXIT:
    STI EXIT_FLAG, #$01
    RET


CHECK_GAME_FLOW:

    LDA BASE_DESTROYED
    CMP A, #$01
    JZ GAME_FLOW_LOST

    LDA PLAYER_LIVES
    CMP A, #$00
    JZ GAME_FLOW_LOST

    LDA ENEMIES_KILLED
    CMP A, #$14
    JNZ GAME_FLOW_DONE

    LDA ENEMIES_ACTIVE
    CMP A, #$00
    JNZ GAME_FLOW_DONE

    CALL SHOW_STAGE_CLEAR

    LDA STAGE_NUM
    CMP A, #$23
    JZ GAME_FLOW_VICTORY

    INC A
    STA STAGE_NUM
    CALL LOAD_STAGE_SCREEN
    RET

GAME_FLOW_VICTORY:
    CALL VICTORY_SCREEN
    LDA EXIT_FLAG
    CMP A, #$01
    JZ GAME_FLOW_DONE
    CALL NEW_GAME
    RET

GAME_FLOW_LOST:
    CALL GAME_OVER_SCREEN
    LDA EXIT_FLAG
    CMP A, #$01
    JZ GAME_FLOW_DONE
    CALL NEW_GAME

GAME_FLOW_DONE:
    RET


