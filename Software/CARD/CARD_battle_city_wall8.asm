    INC A
    LDB NEW_X
    CMP A, B
    JN RECT_NO_COLLISION

    LDA NEW_Y
    INC A
    LDB RECT_Y
    CMP A, B
    JN RECT_NO_COLLISION

    LDA RECT_Y
    INC A
    LDB NEW_Y
    CMP A, B
    JN RECT_NO_COLLISION

    STI COLLISION_FLAG, #$01

