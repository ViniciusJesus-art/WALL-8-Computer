DAMAGE_SELECTED_ENEMY:
    LDA E_HP
    CMP A, #$00
    JZ DAMAGE_ENEMY_DONE
    DEC A
    STA E_HP
    JNZ DAMAGE_ENEMY_SURVIVES

    STI E_ACTIVE, #$00
    CALL SAVE_SELECTED_ENEMY

    LDA ENEMIES_ACTIVE
    CMP A, #$00
    JZ DAMAGE_ACTIVE_READY
    DEC A
    STA ENEMIES_ACTIVE

DAMAGE_ACTIVE_READY:
    LDA ENEMIES_KILLED
    INC A
    STA ENEMIES_KILLED
    STI HUD_DIRTY, #$01

    LDA E_X
    STA EXPLOSION_X
    LDA E_Y
    STA EXPLOSION_Y
    STI EXPLOSION_ACTIVE, #$01
    STI EXPLOSION_TIMER,  #$0C

    CALL ADD_ENEMY_SCORE
    CALL PLAY_EXPLOSION_SOUND

    LDA BONUS_ACTIVE
    CMP A, #$00
    JNZ DAMAGE_ENEMY_DONE
    LDA ENEMIES_KILLED
    TEST A, #$03
    JNZ DAMAGE_ENEMY_DONE

    STI BONUS_ACTIVE, #$01
    LDA E_X
    STA BONUS_X
    LDA E_Y
    STA BONUS_Y
    LDA ENEMIES_KILLED
    SHR A
    SHR A
    AND A, #$03
    STA BONUS_TYPE
    RET

