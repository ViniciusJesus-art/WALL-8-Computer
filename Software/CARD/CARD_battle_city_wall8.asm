    TEST A, #$02
    JNZ EFFECTIVE_DESTROYED
    RET

EFFECTIVE_TEST_BIT2:
    LDA DAMAGE_VALUE
    TEST A, #$04
    JNZ EFFECTIVE_DESTROYED
    RET

