    CALL SAVE_SELECTED_ENEMY
    LDA E_X
    STA EXPLOSION_X
    LDA E_Y
    STA EXPLOSION_Y
    STI EXPLOSION_ACTIVE, #$01
    STI EXPLOSION_TIMER,  #$05
