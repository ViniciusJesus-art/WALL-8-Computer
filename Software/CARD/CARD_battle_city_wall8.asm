    JZ TITLE_START
    CMP A, #$6A
    JZ TITLE_START
    CMP A, #$51
    JZ TITLE_EXIT
    CMP A, #$71
    JZ TITLE_EXIT
    JMP TITLE_WAIT_LOOP

TITLE_START:
    CALL PLAY_START_SOUND
    STI GAME_STATE, #GAME_PLAYING
    RET

TITLE_EXIT:
    STI EXIT_FLAG, #$01
    RET


NEW_GAME:

    STI STAGE_NUM,       #$01
    STI PLAYER_LIVES,    #$03
    STI SCORE_ONES,      #$00
    STI SCORE_TENS,      #$00
