    STA RNG_STATE

    CALL DRAW_FULL_MAP
    CALL DRAW_BASE
    CALL DRAW_GAME_HUD
    CALL SPAWN_INITIAL_ENEMIES
    CALL DRAW_DYNAMIC_OBJECTS
    CALL SYNC_FRAME_STATE
    RET


CLEAR_DAMAGE_MAP:

    PTR DAMAGE_MAP
    STI LOOP_COUNT, #$A9
    CLR A

CLEAR_DAMAGE_LOOP:

    STA [PTR+]

    LDB LOOP_COUNT
    DEC B
    STB LOOP_COUNT
    JNZ CLEAR_DAMAGE_LOOP
    RET


DRAW_FULL_MAP:

    STI MAP_Y_BLOCK, #$00

DRAW_MAP_ROW:

    STI MAP_X_BLOCK, #$00

DRAW_MAP_CELL:

    CALL LOAD_MAP_BLOCK
    STA MAP_TILE_ID

    LDA MAP_X_BLOCK
    SHL A
    STA TARGET_X

    LDA MAP_Y_BLOCK
    SHL A
    STA TARGET_Y

    STI QUADRANT, #$00
    CALL DRAW_TERRAIN_AT_TARGET

    LDA TARGET_X
    INC A
    STA TARGET_X
    STI QUADRANT, #$01
    CALL DRAW_TERRAIN_AT_TARGET

    LDA TARGET_X
    DEC A
    STA TARGET_X
    LDA TARGET_Y
    INC A
    STA TARGET_Y
    STI QUADRANT, #$02
    CALL DRAW_TERRAIN_AT_TARGET

    LDA TARGET_X
    INC A
    STA TARGET_X
    STI QUADRANT, #$03
    CALL DRAW_TERRAIN_AT_TARGET

    LDA MAP_X_BLOCK
    INC A
    STA MAP_X_BLOCK
    CMP A, #$0D
    JNZ DRAW_MAP_CELL

    LDA MAP_Y_BLOCK
    INC A
    STA MAP_Y_BLOCK
    CMP A, #$0D
    JNZ DRAW_MAP_ROW
    RET


; Retorna em A o bloco 0..F nas coordenadas MAP_X_BLOCK / MAP_Y_BLOCK.
; Cada linha original ocupa 7 bytes: 13 nibbles e um nibble de preenchimento.
LOAD_MAP_BLOCK:

    ; OFFSET = MAP_Y_BLOCK * 7 + (MAP_X_BLOCK / 2)
    LDA MAP_Y_BLOCK
    MOV B, A
    SHL A
    SHL A
    SHL A
    SUB A, B
    STA OFFSET_VALUE

    LDA MAP_X_BLOCK
    SHR A
    LDB OFFSET_VALUE
    ADD A, B
    STA OFFSET_VALUE

    CALL SELECT_STAGE_PTR

    LDA OFFSET_VALUE

LOAD_MAP_SEEK:

    CMP A, #$00
    JZ LOAD_MAP_READ
    INC PTR
    DEC A
    JMP LOAD_MAP_SEEK

LOAD_MAP_READ:

    LDA [PTR]

    LDB MAP_X_BLOCK
    TEST B, #$01
    JNZ LOAD_MAP_LOW_NIBBLE

    SHR A
    SHR A
    SHR A
    SHR A
    AND A, #$0F
    RET

LOAD_MAP_LOW_NIBBLE:

    AND A, #$0F
    RET


