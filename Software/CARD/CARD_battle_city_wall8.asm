SUBCELL_TO_BLOCK:

    LDA TARGET_X
    AND A, #$01
    STA QUADRANT

    LDA TARGET_Y
    AND A, #$01
    SHL A
    LDB QUADRANT
    ADD A, B
    STA QUADRANT

    LDA TARGET_X
    SHR A
    STA MAP_X_BLOCK

    LDA TARGET_Y
    SHR A
    STA MAP_Y_BLOCK
    RET


; Retorna A = DAMAGE_MAP[y*13+x] e deixa PTR apontando para esse byte.
LOAD_DAMAGE_MASK:

    LDA MAP_Y_BLOCK
    STA TEMP_VALUE
    SHL A
    SHL A
    SHL A

    LDB TEMP_VALUE
    SHL B
    SHL B
    ADD A, B

    LDB TEMP_VALUE
    ADD A, B

    LDB MAP_X_BLOCK
    ADD A, B
    STA OFFSET_VALUE

    PTR DAMAGE_MAP
    LDA OFFSET_VALUE

LOAD_DAMAGE_SEEK:
    CMP A, #$00
    JZ LOAD_DAMAGE_READ
    INC PTR
    DEC A
    JMP LOAD_DAMAGE_SEEK

LOAD_DAMAGE_READ:
    LDA [PTR]
    RET


