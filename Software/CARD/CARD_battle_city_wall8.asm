LOAD_EFFECTIVE_SUBCELL:

    CALL SUBCELL_TO_BLOCK
    CALL LOAD_MAP_BLOCK
    STA MAP_TILE_ID

    CALL LOAD_DAMAGE_MASK
    STA DAMAGE_VALUE

    LDA QUADRANT
    CMP A, #$00
    JZ EFFECTIVE_TEST_BIT0
    CMP A, #$01
    JZ EFFECTIVE_TEST_BIT1
    CMP A, #$02
    JZ EFFECTIVE_TEST_BIT2

    LDA DAMAGE_VALUE
    TEST A, #$08
    JNZ EFFECTIVE_DESTROYED
    RET

