; ============================================================================
; BATTLE CITY - PORTE COMPLETO 1P PARA WALL-8 / CARD
; ============================================================================
;
; Origem: ROM NES fornecida pelo usuario.
; Alvo:   WALL-8, janela fixa do CARD em $A000-$EFFF (20 KiB).
; Video:  320x240 monocromatico, comando $12.
; Som:    efeitos curtos em TONE/NOISE; sem musica continua.
;
; Esta versao implementa um jogo single-player completo:
;   - os 35 mapas originais;
;   - tiles de tijolo, concreto, agua, floresta, gelo e aguia;
;   - tela de titulo inspirada na original;
;   - jogador, inimigos, IA, projeteis, vidas, pontos e bonus;
;   - destruicao de tijolos, explosoes e progressao das fases;
;   - efeitos TONE/NOISE para tiro, explosao e bonus.
;
; Controles ASCII:
;   W A S D  mover / girar o tanque
;   J ou ESPACO  atirar
;   P        pausar / continuar
;   R        reiniciar a partida
;   Q        retornar a BIOS
;
; A BIOS deve entrar com CALL $A000. O programa NAO inicializa SP e retorna
; com RET, preservando o endereco colocado pela BIOS.
; ============================================================================

