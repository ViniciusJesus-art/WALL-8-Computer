; ============================================================================
; ENTRADA DO CARD
; ============================================================================

INICIO:

    ; A BIOS entrou com CALL $A000. Nao alterar SP.
    STI EXIT_FLAG, #$00
    STI SOUND_CFG, #$00

    CALL VIDEO_WAIT
    STI VIDEO_CMD, #MODE_GFX_320X240
    CALL VIDEO_WAIT

    CALL TITLE_SCREEN

    LDA EXIT_FLAG
    CMP A, #$01
    JZ EXIT_GAME

    CALL NEW_GAME


MAIN_LOOP:

    CALL WAIT_FRAME_NO_INPUT

    CALL ERASE_DYNAMIC_OBJECTS
    CALL POLL_GAME_KEYBOARD

    LDA EXIT_FLAG
    CMP A, #$01
    JZ EXIT_GAME

    LDA GAME_FLAGS
    TEST A, #$01
    JNZ MAIN_LOOP_PAUSED

    CALL UPDATE_GAME_TIMERS
    CALL UPDATE_PLAYER_BULLET
    CALL UPDATE_ENEMY_BULLETS
    CALL UPDATE_ENEMIES
    CALL UPDATE_SPAWNER
    CALL CHECK_BONUS_COLLECTION
    CALL DRAW_DYNAMIC_OBJECTS
    CALL DRAW_DYNAMIC_HUD
    CALL CHECK_GAME_FLOW

    JMP MAIN_LOOP

MAIN_LOOP_PAUSED:
    CALL UPDATE_SOUND
    CALL DRAW_DYNAMIC_OBJECTS
    JMP MAIN_LOOP


EXIT_GAME:

    CALL VIDEO_WAIT
    STI SOUND_CFG, #$00
    RET


; ============================================================================
; TELAS E FLUXO DA PARTIDA
; ============================================================================

TITLE_SCREEN:

    STI GAME_STATE, #GAME_TITLE
    STI SCREEN_ACTION, #$00
    STI SOUND_CFG, #$00
    STI SOUND_TIMER, #$00

    CALL VIDEO_WAIT
    STI VIDEO_CMD, #VIDEO_CLEAR
    CALL VIDEO_WAIT

    ; Logotipo grande, monocromatico, inspirado na composicao do NES.
    STI DRAW_SCREEN_X, #$0E
    STI DRAW_PIXEL_Y,  #$20
    STI DRAW_WIDTH,    #$0C
    STI DRAW_ROWS,     #$10
    PTR TITLE_BATTLE_LARGE
    CALL DRAW_BITMAP_ROWS

    STI DRAW_SCREEN_X, #$10
    STI DRAW_PIXEL_Y,  #$38
    STI DRAW_WIDTH,    #$08
    STI DRAW_ROWS,     #$10
    PTR TITLE_CITY_LARGE
    CALL DRAW_BITMAP_ROWS

    STI DRAW_SCREEN_X, #$10
    STI DRAW_PIXEL_Y,  #$70
    STI DRAW_WIDTH,    #$08
    PTR TITLE_1_PLAYER
    CALL DRAW_BITMAP8

    STI DRAW_SCREEN_X, #$0E
    STI DRAW_PIXEL_Y,  #$90
    STI DRAW_WIDTH,    #$0B
    PTR TITLE_PRESS_ENTER
    CALL DRAW_BITMAP8

    STI DRAW_SCREEN_X, #$0E
    STI DRAW_PIXEL_Y,  #$B8
    STI DRAW_WIDTH,    #$0B
    PTR TITLE_WALL8_CARD
    CALL DRAW_BITMAP8

    STI DRAW_SCREEN_X, #$11
    STI DRAW_PIXEL_Y,  #$D0
    STI DRAW_WIDTH,    #$06
    PTR TITLE_Q_EXIT
    CALL DRAW_BITMAP8

    ; Dois tanques enquadram a opcao de jogador.
    STI DRAW_SCREEN_X, #$0C
    STI DRAW_PIXEL_Y,  #$68
    PTR TANK_RIGHT
    CALL DRAW_PATTERN16

    STI DRAW_SCREEN_X, #$1C
    STI DRAW_PIXEL_Y,  #$68
    PTR ENEMY_0_LEFT
    CALL DRAW_PATTERN16

    CALL SYNC_FRAME_STATE

TITLE_WAIT_LOOP:
    CALL WAIT_FRAME_NO_INPUT
    CALL UPDATE_SOUND

    LDA SYSTEM_STATUS
    TEST A, #KEY_READY_MASK
    JZ TITLE_WAIT_LOOP

    LDA KEY_DATA
    CMP A, #$0D
    JZ TITLE_START
    CMP A, #$20
    JZ TITLE_START
