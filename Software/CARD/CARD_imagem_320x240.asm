; ============================================================================
; WALL-8 - Cartucho de imagem monocromatica 320x240
;
; A imagem abaixo possui exatamente:
;   320 x 240 pixels
;   1 bit por pixel
;   40 bytes por linha
;   240 linhas
;   9.600 bytes de framebuffer
;
; A BIOS deve chamar o cartucho com:
;   CALL $A000
;
; O cartucho:
;   1. seleciona o modo grafico 320x240;
;   2. limpa a VRAM;
;   3. posiciona VIDEO_X/VIDEO_Y em 0,0;
;   4. le os bytes da imagem da ROM usando LDA [PTR+];
;   5. envia um byte de cada vez para VIDEO_DATA;
;   6. espera BUSY terminar antes do proximo byte;
;   7. termina quando VIDEO_STATUS.CURSOR_END = 1.
;
; Bit 7 de cada byte = pixel mais a esquerda do grupo de 8 pixels.
; ============================================================================

VIDEO_DATA       = $F200
VIDEO_CMD        = $F201
VIDEO_X          = $F202
VIDEO_Y          = $F203
VIDEO_STATUS     = $F204

VIDEO_BUSY_MASK  = $01
VIDEO_END_MASK   = $10

VIDEO_CLEAR      = $00
VIDEO_MODE_320   = $12


INICIO:

    ; Espera a GPU ficar livre.
    CALL VIDEO_WAIT

    ; Seleciona grafico monocromatico 320x240.
    STI VIDEO_CMD, #VIDEO_MODE_320
    CALL VIDEO_WAIT

    ; Limpa os 9.600 bytes usados pelo framebuffer.
    STI VIDEO_CMD, #VIDEO_CLEAR
    CALL VIDEO_WAIT

    ; Inicio do framebuffer.
    STI VIDEO_X, #$00
    STI VIDEO_Y, #$00

    ; PTR aponta para os 9.600 bytes da imagem dentro do proprio cartucho.
    PTR IMAGE_DATA


IMAGE_LOOP:

    ; Le o proximo byte da ROM e incrementa PTR.
    LDA [PTR+]

    ; VIDEO_DATA so pode ser alterado quando BUSY = 0.
    CALL VIDEO_WRITE_A

    ; VIDEO_WRITE_A retorna somente depois que a escrita terminou.
    ; Na ultima posicao (X=39,Y=239), CURSOR_END fica em 1.
    LDA VIDEO_STATUS
    TEST A, #VIDEO_END_MASK
    JZ IMAGE_LOOP


IMAGE_DONE:

    ; Mantem a imagem na tela.
    JMP IMAGE_DONE

    ; Se futuramente quiser retornar para a BIOS:
    ; RET


; ----------------------------------------------------------------------------
; Espera BUSY = 0.
; VIDEO_STATUS bit 0 = BUSY.
; ----------------------------------------------------------------------------
VIDEO_WAIT:

    LDA VIDEO_STATUS
    TEST A, #VIDEO_BUSY_MASK
    JNZ VIDEO_WAIT
    RET


; ----------------------------------------------------------------------------
; Entrada:
;   A = byte grafico a ser escrito.
;
; Guarda A temporariamente em B porque VIDEO_WAIT usa A para ler VIDEO_STATUS.
; ----------------------------------------------------------------------------
VIDEO_WRITE_A:

    MOV B, A

VIDEO_WRITE_WAIT:

    LDA VIDEO_STATUS
    TEST A, #VIDEO_BUSY_MASK
    JNZ VIDEO_WRITE_WAIT

    MOV A, B
    STA VIDEO_DATA

    ; Espera a GPU concluir a escrita e atualizar X/Y/CURSOR_END.
VIDEO_WRITE_FINISH:

    LDA VIDEO_STATUS
    TEST A, #VIDEO_BUSY_MASK
    JNZ VIDEO_WRITE_FINISH

    RET


